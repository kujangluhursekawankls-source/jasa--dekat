/**
 * Helper to get list of districts for a given city name
 */
export function getDistrictsForCity(cityName: string): string[] {
  if (!cityName) return [];
  const cleanCity = cityName.trim().toLowerCase();
  for (const region of INDONESIAN_REGIONS) {
    const matched = region.cities.find((c) => c.name.toLowerCase() === cleanCity);
    if (matched) {
      return [...matched.districts].sort((a, b) => a.localeCompare(b));
    }
  }
  return [];
}

/**
 * Helper to get list of cities for a given province name
 */
export function getCitiesForProvince(provinceName: string): string[] {
  if (!provinceName) return [];
  const cleanProv = provinceName.trim().toLowerCase();
  const region = INDONESIAN_REGIONS.find((r) => r.province.toLowerCase() === cleanProv);
  if (!region) return [];
  return region.cities.map((c) => c.name);
}

